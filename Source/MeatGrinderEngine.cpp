MeatGrinderEngine::MeatGrinderEngine()
{
    for (auto& d : delayBuf)
        d.assign ((size_t) kDelayCap, 0.0f);
}

void MeatGrinderEngine::prepare (double sampleRate, int /*maxBlockSize*/)
{
    fs = sampleRate;

    for (auto& d : delayBuf)
        d.assign ((size_t) kDelayCap, 0.0f);
    delayPos = 0;

    using OS = juce::dsp::Oversampling<float>;
    oversamplers[1] = std::make_unique<OS> (2, 1, OS::filterHalfBandFIREquiripple, true, true);
    oversamplers[2] = std::make_unique<OS> (2, 2, OS::filterHalfBandFIREquiripple, true, true);
    for (size_t i = 1; i < 3; ++i)
        oversamplers[i]->initProcessing ((size_t) kChunk);

    for (auto* sm : { &fatSm, &colSm, &punchSm, &mixSm, &outSm, &compSm })
        sm->reset (fs, 0.03);
    bypassSm.reset (fs, 0.012);
    driveSm.reset (fs, 0.03);

    auto coef = [this] (double seconds) { return 1.0f - std::exp (-1.0f / (float) (seconds * fs)); };
    tfAtt = coef (0.00005);  tfRel = coef (0.04);    // fast transient envelope (peak follower)
    tsAtt = coef (0.08);                             // slow reference: symmetric smoother of the fast envelope
    pkRel = coef (0.045);    rmsCoef = coef (0.12);
    msCoef = coef (0.30);    compCoef = coef (0.15);
    dcR = 1.0 - 2.0 * juce::MathConstants<double>::pi * 10.0 / fs;

    osIndex = -1;
    setOversampling (1);
    lastColor = -1.0f;
    prepared = true;
    reset();
}

void MeatGrinderEngine::reset()
{
    for (auto& d : delayBuf)
        d.assign ((size_t) kDelayCap, 0.0f);
    delayPos = 0;
    resetDsp();
    wasBypassed = false;
    firstBlock = true;
}

void MeatGrinderEngine::resetDsp()
{
    for (auto& c : ch)
        c.reset();
    if (osIndex > 0 && oversamplers[(size_t) osIndex] != nullptr)
        oversamplers[(size_t) osIndex]->reset();
    envF = envS = pk = rmsMs = 0.0f;
    msDry = msWet = 0.0f;
    compGain = 1.0f;
    nanSeen = false;
}

void MeatGrinderEngine::setOversampling (int index)
{
    index = juce::jlimit (0, 2, index);
    osIndex = index;
    osFactor = 1 << index;

    if (index > 0)
    {
        oversamplers[(size_t) index]->reset();
        latency = (int) std::lround (oversamplers[(size_t) index]->getLatencyInSamples());
    }
    else
    {
        latency = 0;
    }
    delaySamples = juce::jmin (latency, kDelayCap - 1);

    const double osFs = fs * osFactor;
    for (auto& c : ch)
    {
        c.exHp1.makeHighPass (osFs, 1800.0, 0.7071);
        c.exHp2.makeHighPass (osFs, 3500.0, 0.7071);
        c.exHp1.reset();
        c.exHp2.reset();
        c.exEnv = 0.0f;
    }
    osDcR = 1.0 - 2.0 * juce::MathConstants<double>::pi * 10.0 / osFs;
    exAtt = 1.0f - std::exp (-1.0f / (float) (0.0002 * osFs));
    exRel = 1.0f - std::exp (-1.0f / (float) (0.005 * osFs));
    lastColor = -1.0f;
}

void MeatGrinderEngine::setOversamplingMode (int index)
{
    if (prepared && juce::jlimit (0, 2, index) != osIndex)
        setOversampling (index);
}

void MeatGrinderEngine::applySettings (const Settings& s)
{
    cur = s;
    const float drive = dbToGain (juce::jlimit (0.0f, 36.0f, s.driveDb));
    const float outG = dbToGain (juce::jlimit (-24.0f, 12.0f, s.outputDb));

    fatSm.setTargetValue (juce::jlimit (0.0f, 1.0f, s.fatness));
    colSm.setTargetValue (juce::jlimit (0.0f, 1.0f, s.color));
    punchSm.setTargetValue (juce::jlimit (0.0f, 1.0f, s.punch));
    mixSm.setTargetValue (juce::jlimit (0.0f, 1.0f, s.mix));
    outSm.setTargetValue (outG);
    driveSm.setTargetValue (drive);
    bypassSm.setTargetValue (s.bypass ? 1.0f : 0.0f);
    compSm.setTargetValue (s.gainComp ? 1.0f : 0.0f);

    if (firstBlock)
    {
        for (auto* sm : { &fatSm, &colSm, &punchSm, &mixSm, &outSm, &bypassSm, &compSm })
            sm->setCurrentAndTargetValue (sm->getTargetValue());
        driveSm.setCurrentAndTargetValue (drive);
        firstBlock = false;
    }
}

void MeatGrinderEngine::updateColor (float c)
{
    if (std::fabs (c - lastColor) < 1.0e-4f)
        return;
    lastColor = c;

    const double cb = 2.0 * (double) c - 1.0;     // -1 (warm) .. +1 (bright)
    ch[0].preShelf.makeHighShelf (fs, 1200.0, 6.0 * cb, 0.7071);     // what drives the saturator
    ch[0].postShelf.makeHighShelf (fs, 1200.0, 2.5 * cb, 0.7071);    // tone of the saturated result (also lifts generated harmonics)

    toneActive = c < 0.499f;
    if (toneActive)
    {
        const double fc = juce::jmin (20000.0 * std::pow (0.25, 1.0 - 2.0 * (double) c), 0.45 * fs);
        ch[0].tone.makeLowPass (fs, fc, 0.7071);
    }

    auto copy = [] (Biquad& d, const Biquad& s) { d.b0 = s.b0; d.b1 = s.b1; d.b2 = s.b2; d.a1 = s.a1; d.a2 = s.a2; };
    copy (ch[1].preShelf, ch[0].preShelf);
    copy (ch[1].postShelf, ch[0].postShelf);
    copy (ch[1].tone, ch[0].tone);
}

void MeatGrinderEngine::updateDynamicsCoefficients (float punch)
{
    densAmt = 1.0f - punch;
    densRatio = 1.0f + 7.0f * densAmt * densAmt;
    duckAmt = punch;
    pkAtt = 1.0f - std::exp (-1.0f / (float) ((0.0004 + 0.006 * (double) punch) * fs));
}

void MeatGrinderEngine::runShaper (int chIdx, float* data, int num) noexcept
{
    auto& c = ch[(size_t) chIdx];
    const float ex = shaper.exciter;

    // DC is removed *before* the ceiling (inside the oversampled stage), so that removing the offset of an
    // asymmetric clipped wave can never push its minority side past the ceiling afterwards.
    auto finish = [this] (Channel& cs, float y) noexcept
    {
        const double yd = (double) y - cs.osDcX + osDcR * cs.osDcY;
        cs.osDcX = (double) y;
        cs.osDcY = yd;
        return applyCeiling ((float) yd, shaper);
    };

    if (ex > 1.0e-4f)
    {
        // Harmonic exciter.  The band above ~1.8 kHz is normalised by its own envelope and pushed through a
        // bounded cubic (2nd + 3rd harmonics only), then scaled back by the envelope.  Nothing hard-clips,
        // so the exciter stays alias-free at any DRIVE and adds harmonics in proportion to the HF content.
        for (int i = 0; i < num; ++i)
        {
            const float u = data[i];
            const float h = c.exHp1.process (u);
            const float a = std::fabs (h);
            c.exEnv += (a > c.exEnv ? exAtt : exRel) * (a - c.exEnv);
            const float hn = juce::jlimit (-1.5f, 1.5f, h / (c.exEnv + 1.0e-3f));
            const float raw = c.exHp2.process (hn * hn * (0.7f + 0.3f * hn)) * c.exEnv;   // DC removed by the HP
            data[i] = finish (c, shapeCore (u, shaper) + ex * raw);
        }
    }
    else
    {
        for (int i = 0; i < num; ++i)
            data[i] = finish (c, shapeCore (data[i], shaper));
    }
}

void MeatGrinderEngine::process (juce::AudioBuffer<float>& buffer, const Settings& s)
{
    const int numCh = juce::jmin (buffer.getNumChannels(), 2);
    const int n = buffer.getNumSamples();
    if (! prepared || numCh < 1 || n < 1)
        return;

    if (juce::jlimit (0, 2, s.oversampling) != osIndex)
        setOversampling (s.oversampling);

    applySettings (s);

    for (int pos = 0; pos < n; pos += kChunk)
        processChunk (buffer, pos, juce::jmin (kChunk, n - pos), numCh);
}

void MeatGrinderEngine::processChunk (juce::AudioBuffer<float>& buffer, int start, int m, int numCh)
{
    // ---- 1. capture input, meter it ------------------------------------------------
    float pkIn[2] = { 0.0f, 0.0f };
    for (int c = 0; c < 2; ++c)
    {
        const float* src = buffer.getReadPointer (juce::jmin (c, numCh - 1)) + start;
        auto& dst = inBuf[(size_t) c];
        float p = 0.0f;
        for (int i = 0; i < m; ++i)
        {
            const float x = src[i];
            dst[(size_t) i] = x;
            p = std::max (p, std::fabs (x));
        }
        pkIn[c] = p;
    }
    for (int c = 0; c < numCh; ++c)
        raisePeak (meters.inPeak[c], pkIn[c]);
    if (pkIn[0] >= 1.0f || pkIn[1] >= 1.0f)
        meters.inClip.store (true, std::memory_order_relaxed);

    // ---- 2. latency-aligned dry signal ----------------------------------------------
    constexpr int mask = kDelayCap - 1;
    for (int c = 0; c < 2; ++c)
    {
        auto& db = delayBuf[(size_t) c];
        int w = delayPos;
        for (int i = 0; i < m; ++i)
        {
            db[(size_t) (w & mask)] = inBuf[(size_t) c][(size_t) i];
            dryAl[(size_t) c][(size_t) i] = db[(size_t) ((w - delaySamples) & mask)];
            ++w;
        }
    }
    delayPos = (delayPos + m) & mask;

    float* outp[2] = { buffer.getWritePointer (0) + start,
                       numCh > 1 ? buffer.getWritePointer (1) + start : nullptr };

    // ---- 3. fully bypassed: just the aligned dry --------------------------------------
    if (bypassSm.getTargetValue() >= 1.0f && bypassSm.getCurrentValue() >= 1.0f)
    {
        if (! wasBypassed)
        {
            resetDsp();
            wasBypassed = true;
        }
        float pkOut[2] = { 0.0f, 0.0f };
        for (int c = 0; c < numCh; ++c)
            for (int i = 0; i < m; ++i)
            {
                const float v = dryAl[(size_t) c][(size_t) i];
                outp[c][i] = v;
                pkOut[c] = std::max (pkOut[c], std::fabs (v));
            }
        for (int c = 0; c < numCh; ++c)
            raisePeak (meters.outPeak[c], pkOut[c]);
        if (pkOut[0] >= 1.0f || pkOut[1] >= 1.0f)
            meters.outClip.store (true, std::memory_order_relaxed);
        return;
    }
    wasBypassed = false;

    // ---- 4. control-rate updates -----------------------------------------------------
    const float F = fatSm.skip (m);
    const float col = colSm.skip (m);
    const float pun = punchSm.skip (m);
    shaper = makeShaperParams (F, col, cur.hardClip);
    updateColor (col);
    updateDynamicsCoefficients (pun);

    float compTarget = compGain;
    if (msDry > 1.0e-9f && msWet > 1.0e-12f)
        compTarget = juce::jlimit (0.001f, 8.0f, std::sqrt (msDry / msWet));

    // ---- 5. pre-stage: drive, density compressor, transient duck, colour pre-emphasis ---
    for (int i = 0; i < m; ++i)
    {
        const float g = driveSm.getNextValue();
        const float vL = inBuf[0][(size_t) i] * g;
        const float vR = inBuf[1][(size_t) i] * g;
        const float a = std::max (std::fabs (vL), std::fabs (vR));

        envF += ((a > envF) ? tfAtt : tfRel) * (a - envF);
        envS += tsAtt * (envF - envS);               // zero bias on steady signals, lags behind on onsets
        pk += ((a > pk) ? pkAtt : pkRel) * (a - pk);
        rmsMs += rmsCoef * (0.5f * (vL * vL + vR * vR) - rmsMs);

        float duck = 1.0f, gd = 1.0f;
        if (duckAmt > 0.001f)
        {
            const float tDb = kLn2dB * std::log2 ((envF + 1.0e-6f) / (envS + 1.0e-6f));
            const float t = juce::jlimit (0.0f, 1.0f, tDb * (1.0f / 9.0f));
            duck = std::exp2 (-duckAmt * t * 8.0f * kDbToExp2);
        }
        if (densAmt > 0.001f)
        {
            const float rms = std::sqrt (rmsMs) + 1.0e-6f;
            const float crest = kLn2dB * std::log2 ((pk + 1.0e-6f) / rms);
            const float over = crest - kCrestThreshDb;
            if (over > 0.0f)
            {
                const float red = std::min (over * (1.0f - 1.0f / densRatio), 18.0f);
                gd = std::exp2 (-red * kDbToExp2);
            }
        }

        const float k = gd * duck;
        duckBuf[(size_t) i] = duck;
        work[0][(size_t) i] = ch[0].preShelf.process (vL * k);
        work[1][(size_t) i] = ch[1].preShelf.process (vR * k);
    }

    // ---- 6. nonlinear stages (oversampled) --------------------------------------------
    if (osIndex == 0)
    {
        runShaper (0, work[0].data(), m);
        runShaper (1, work[1].data(), m);
    }
    else
    {
        float* ptrs[2] = { work[0].data(), work[1].data() };
        juce::dsp::AudioBlock<float> blk (ptrs, 2, (size_t) m);
        auto& os = *oversamplers[(size_t) osIndex];
        auto up = os.processSamplesUp (juce::dsp::AudioBlock<const float> (blk));
        runShaper (0, up.getChannelPointer (0), (int) up.getNumSamples());
        runShaper (1, up.getChannelPointer (1), (int) up.getNumSamples());
        os.processSamplesDown (blk);
    }

    // ---- 7. post-stage: DC block, colour de-emphasis + tone, gain comp, mix, output ---
    const bool hard = cur.hardClip;
    float pkOut[2] = { 0.0f, 0.0f };

    for (int i = 0; i < m; ++i)
    {
        const float invDuck = std::min (1.0f / duckBuf[(size_t) i], kMaxPunchLift);   // transients may stick out of the saturated body, but only into the headroom
        float w[2];
        for (int c = 0; c < 2; ++c)
        {
            auto& cs = ch[(size_t) c];
            const double x = (double) (work[(size_t) c][(size_t) i] * invDuck);
            const double yDc = x - cs.dcX + dcR * cs.dcY;
            cs.dcX = x;
            cs.dcY = yDc;

            float y = cs.postShelf.process ((float) yDc);
            if (toneActive)
                y = cs.tone.process (y);
            w[c] = y;
        }

        const float dL = dryAl[0][(size_t) i], dR = dryAl[1][(size_t) i];
        msWet += msCoef * (0.5f * (w[0] * w[0] + w[1] * w[1]) - msWet);
        msDry += msCoef * (0.5f * (dL * dL + dR * dR) - msDry);
        compGain += compCoef * (compTarget - compGain);

        const float gc = 1.0f + compSm.getNextValue() * (compGain - 1.0f);
        const float mixv = mixSm.getNextValue();
        const float og = outSm.getNextValue();
        const float byp = bypassSm.getNextValue();

        for (int c = 0; c < numCh; ++c)
        {
            float wet = w[c] * gc;
            wet = hard ? juce::jlimit (-1.0f, 1.0f, wet) : softCeiling (wet, kOuterKnee, 1.0f);   // safety ceiling (overshoot only)

            const float dry = dryAl[(size_t) c][(size_t) i];
            const float proc = (dry + mixv * (wet - dry)) * og;
            float out = proc + byp * (dry - proc);

            if (! std::isfinite (out))
            {
                out = 0.0f;
                nanSeen = true;
            }
            out = juce::jlimit (-kGuard, kGuard, out);
            outp[c][i] = out;
            pkOut[c] = std::max (pkOut[c], std::fabs (out));
        }
    }

    for (int c = 0; c < numCh; ++c)
        raisePeak (meters.outPeak[c], pkOut[c]);
    if (pkOut[0] >= 1.0f || pkOut[1] >= 1.0f)
        meters.outClip.store (true, std::memory_order_relaxed);

    if (nanSeen)
        resetDsp();
}

